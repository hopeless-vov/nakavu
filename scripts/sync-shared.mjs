// Copies the pure logic in shared/ into supabase/functions/_shared/lib/ so Edge
// Functions (Deno) bundle the exact same code the app uses, and generates the
// labels emails need (catalogue + conversation starters) from i18n/locales.
// Run after editing shared/ or those locale keys: `npm run sync:shared`.
// A unit test fails if the copies drift.
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'

const target = 'supabase/functions/_shared/lib'
mkdirSync(target, { recursive: true })
for (const file of readdirSync('shared').filter((f) => f.endsWith('.ts'))) {
  copyFileSync(`shared/${file}`, `${target}/${file}`)
  console.log(`shared/${file} → ${target}/${file}`)
}

export function labelsSource() {
  const labels = {}
  for (const code of ['uk', 'en', 'nl']) {
    const m = JSON.parse(readFileSync(`i18n/locales/${code}.json`, 'utf8'))
    labels[code] = { catalog: m.catalog, starters: m.starters }
  }
  return `// Generated by scripts/sync-shared.mjs from i18n/locales — do not edit.\nexport const LABELS = ${JSON.stringify(labels, null, 2)} as const\n`
}

writeFileSync(`${target}/labels.ts`, labelsSource())
console.log(`i18n/locales → ${target}/labels.ts`)
